import mongoose from "mongoose";

const UserSchema = new mongoose.Schema(
  {
    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true,
    },
    passwordHash: {
      type: String,
      required: true,
    },
  },
  { timestamps: true }
);

// Avoid recompiling the model on every hot-reload / serverless invocation.
export default mongoose.models.User || mongoose.model("User", UserSchema);
